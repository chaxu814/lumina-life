const DICT: Set<string> = new Set([...WORDS_2, ...WORDS_3, ...WORDS_4])

/** 词表最长长度（用于匹配窗口） */
const MAX_WORD_LEN = 4
const MIN_WORD_LEN = 2

/**
 * 对一段**纯 CJK 文本**做词表最长匹配，返回命中的词（可重复）。
 * 未命中任何词时返回空数组 —— 调用方保留原有的 unigram+bigram。
 *
 * 匹配策略：从每个位置起，按 4→3→2 的长度尝试，命中即收录并**跳过该词长度**，
 * 避免重叠词互相干扰（如「人工智能」命中后不再产出「人工」「智能」）。
 */
export function dictMatch(run: string): string[] {
  const chars = Array.from(run)
  const out: string[] = []
  let i = 0
  while (i < chars.length) {
    let matched = 0
    for (let len = Math.min(MAX_WORD_LEN, chars.length - i); len >= MIN_WORD_LEN; len--) {
      const w = chars.slice(i, i + len).join('')
      if (DICT.has(w)) {
        out.push(w)
        matched = len
        break
      }
    }
    i += matched > 0 ? matched : 1
  }
  return out
}

/** 供测试/统计：词表规模 */
export function dictSize(): number {
  return DICT.size
}

// 【要解决的问题】
//   原分词是纯 unigram + bigram（按字切），例如「苹果手机」会切成
//   苹/果/手/机/苹果/果手/手机 —— 能召回，但会产生大量无意义二字组合
//   （果手），且「手机」这类词和「手」「机」权重混在一起，精度有限。
//
// 【方案：内置词表做「最长匹配」补充】
//   不引入任何 npm 依赖（Electron 原生模块会带来打包/ABI 问题），
//   改用一份**内置常用词表**做最长匹配，把命中的词作为额外 token 加进去。
//
// 【为什么是「补充」而不是「替换」】
//   保留 unigram + bigram，只是**额外**加词表命中的词。
//   这样只会增加匹配机会、不会降低召回 —— 属于严格的安全增强。
//   对高频词表词，BM25 的 IDF 会自然压低其权重，不会污染排序。
//
// 【可关闭】memory.cjkDict 开关（默认开）。关掉即回到纯 unigram+bigram。
// ============================================================


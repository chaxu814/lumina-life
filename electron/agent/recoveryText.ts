/**
 * recoveryText — 恢复流程的文本取舍（纯函数，可单测）
 *
 * ============================================================
 * 【为什么需要这个模块】
 *
 * `agentRunner` 的恢复流程里有一条「总结轮」：ReAct 循环耗尽且拿不到任何
 * assistant 文本时，会**故意不带工具**（`callLLM([])`）再问模型一次，希望
 * 它把本轮对话浓缩成一句自然语言回复。提示词也明确写了「不要调用工具」。
 *
 * 但小模型经常无视该指令 —— 实测 4B 档（QwenPaw Flash 4B Q4）在总结轮里
 * 仍然输出 XML 工具调用。此时 `callLLM` 会把它替换成一段**诊断文案**：
 *
 *   「（我本来想调用一个工具，但这轮没有可用的工具，所以没能执行。
 *      你可以换个说法，或到设置里检查工具是否被关闭。）」
 *
 * 这段文案的用途是「在**用户可见的轮次**里，诚实说明模型为什么没做成事」，
 * 而不是「回答用户的问题」。旧实现直接把它当成总结结果上屏，于是：
 *
 *   · 用户问「A股今天的情况是什么」
 *   · 聊久了（长对话更容易让循环耗尽）之后，突然收到一句
 *     「我本来想调用一个工具，但这轮没有可用的工具」
 *   · 而且它把用户引向「到设置里检查工具是否被关闭」这个**错误的排查方向**
 *
 * 【正确的取舍】
 * 丢弃它、让文本保持为空，继续走下一级兜底（简化上下文的无工具恢复），
 * 那才是真正的出路。宁可多走一级，也不把内部诊断当回答。
 *
 * 这个判断被抽成纯函数，是因为它**没法靠联网测试发现** ——
 * 它不报错、不崩溃，只是在特定上下文长度 + 特定模型上偶发。
 * ============================================================
 */

/** `callLLM` 返回值里与本模块相关的字段子集 */
export interface RecoveryLLMResult {
  text?: string
  /**
   * `text` 是「模型想调工具但本轮没给工具」的诊断说明，**不是**对问题的回答。
   * 见 `agentRunner.callLLM` 的 `tools.length === 0` 分支。
   */
  noToolsHint?: boolean
}

// ═══════════════════════════════════════════════════════════
// 🐛 2026-10-17：模型**复述/评论总结指令本身**（第二种泄漏）
//
// 【现象】团队群聊里，队友接话时突然说：
//   「你说要"根据本轮对话"来回复，但这一轮里好像没有给我提供具体的对话内容
//     或搜索结果啊？是漏传了材料吗？」
//   「这一轮确实没有实际调用任何工具。因为按照规则，只有在需要写文件、
//     执行命令或搜索信息时才用工具……」
//
// 【成因】总结轮的指令是伪造的 user 消息。当本轮上下文很薄（群聊接话就是
//   这种情况：`conversationHistory` 按 Agent 隔离后可能几乎为空），模型
//   没有可总结的内容，于是**把这条指令本身当成话题来回应** ——
//   它没编造事实，也没报错，只是对着指令说话。
//
//   这比"编造"更隐蔽：文本读起来通顺、语气也对，所以旧的
//   `noToolsHint` 判断和长度判断都放行了，直接上屏。
//
// 【本模块的职责】把这类文本识别为「无内容」，交给下一级兜底。
//   宁可最终给一句诚实的"这轮没能给出有效回复"，也不要让用户看到
//   模型在念内部指令 —— 后者会让用户以为软件漏传了数据。
// ═══════════════════════════════════════════════════════════

/**
 * 「复述/评论指令」的强特征。
 *
 * 判定口径刻意取窄：只收**正常回答里几乎不可能出现**的说法。
 * 例如用户真问「你刚才为什么没调用工具」，模型会答"因为不需要"，
 * 不会说"这一轮确实没有实际调用任何工具" —— 后者是在描述轮次机制。
 */
const INSTRUCTION_ECHO_PATTERNS: RegExp[] = [
  // 直接引述指令：「你说要…回复」
  /你说要[^。！？\n]{0,24}(回复|回答|作答|总结)/,
  // 引述指令原文
  /根据本轮对话/,
  // 抱怨材料没给：「漏传了材料」「没给我提供具体的对话内容」
  /(漏传|漏给|少传|没传|没给我提供|没有给我提供)[^。！？\n]{0,16}(材料|内容|对话|上下文|搜索结果)/,
  // 描述轮次机制：「这一轮/本轮没有（可用的）工具」
  /(本轮|这一轮)(里|中)?(确实)?(没有|没)(实际)?(调用|使用)?(任何)?(可用的)?工具/,
  // 引述工具规则：「按照规则，只有在需要…时才用工具」
  /按(照)?规则[，,：:][^。！？\n]{0,40}(工具|调用)/,
  // 指代指令本身：「这条指令」「这个系统提示」
  /(这条|这个)(系统)?(指令|提示词|提示)(是|要|让|说|要求)/,
  // 把「群聊场记」外框抄进回复（`conversationDynamics.SPARK_NOTE_PREFIX`）。
  //   「场记」这个词正常对话里绝不会出现 —— 出现就一定是模型在念提示词。
  /群聊场记|【[^】\n]{0,10}场记/,
]

/** 弱特征：单独出现不算，两条以上才判为复述 */
const INSTRUCTION_ECHO_WEAK: RegExp[] = [
  /(本轮|这一轮)/,
  /系统(提示|指令)/,
  /(调用|使用|用)工具/,
  /(材料|上下文)(够|不足|不全|没有)/,
]

/**
 * 这段文本是不是在**谈论指令/轮次机制**，而不是在回答用户？
 *
 * @returns true 表示「不该上屏」，调用方应把它当作空内容处理。
 */
export function isInstructionEcho(text: string): boolean {
  const s = String(text || '').trim()
  if (!s) {return false}
  // 正常回答可以很长；但复述指令通常不会长到离谱。
  // 这里不按长度硬卡，避免误杀「认真解释自己为什么没调工具」的长回答。
  if (INSTRUCTION_ECHO_PATTERNS.some(re => re.test(s))) {return true}
  const weakHits = INSTRUCTION_ECHO_WEAK.filter(re => re.test(s)).length
  return weakHits >= 2 && s.length < 400
}

/**
 * 从总结轮的返回里挑出**可以当作回复**的文本。
 *
 * - 诊断文案（`noToolsHint`）→ 返回空串（丢弃，交给下一级兜底）
 * - 复述/评论指令（`isInstructionEcho`）→ 返回空串（同上）
 * - 正常文本 → 返回 trim 后的结果
 * - 空 / 缺字段 / null → 空串
 */
export function pickRecoverySummaryText(resp: RecoveryLLMResult | null | undefined): string {
  if (!resp) {return ''}
  if (resp.noToolsHint) {return ''}
  const text = String(resp.text || '').trim()
  if (!text) {return ''}
  if (isInstructionEcho(text)) {return ''}
  return text
}

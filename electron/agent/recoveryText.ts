/**
 * recoveryText — 恢复流程的文本取舍（纯函数，可单测）
 *
 * ============================================================
 * 【为什么需要这个模块】
 *
 * `agentRunner` 的恢复流程里有一条「总结轮」：ReAct 循环耗尽且拿不到任何
 * assistant 文本时，会**故意不带工具**（`callLLM([])`）再问模型一次，希望
 * 它把本轮对话浓缩成一句自然语言回复。提示词也明确写了「不要调用工具」。
 *
 * 但小模型经常无视该指令 —— 实测 4B 档（QwenPaw Flash 4B Q4）在总结轮里
 * 仍然输出 XML 工具调用。此时 `callLLM` 会把它替换成一段**诊断文案**：
 *
 *   「（我本来想调用一个工具，但这轮没有可用的工具，所以没能执行。
 *      你可以换个说法，或到设置里检查工具是否被关闭。）」
 *
 * 这段文案的用途是「在**用户可见的轮次**里，诚实说明模型为什么没做成事」，
 * 而不是「回答用户的问题」。旧实现直接把它当成总结结果上屏，于是：
 *
 *   · 用户问「A股今天的情况是什么」
 *   · 聊久了（长对话更容易让循环耗尽）之后，突然收到一句
 *     「我本来想调用一个工具，但这轮没有可用的工具」
 *   · 而且它把用户引向「到设置里检查工具是否被关闭」这个**错误的排查方向**
 *
 * 【正确的取舍】
 * 丢弃它、让文本保持为空，继续走下一级兜底（简化上下文的无工具恢复），
 * 那才是真正的出路。宁可多走一级，也不把内部诊断当回答。
 *
 * 这个判断被抽成纯函数，是因为它**没法靠联网测试发现** ——
 * 它不报错、不崩溃，只是在特定上下文长度 + 特定模型上偶发。
 * ============================================================
 */

/** `callLLM` 返回值里与本模块相关的字段子集 */
export interface RecoveryLLMResult {
  text?: string
  /**
   * `text` 是「模型想调工具但本轮没给工具」的诊断说明，**不是**对问题的回答。
   * 见 `agentRunner.callLLM` 的 `tools.length === 0` 分支。
   */
  noToolsHint?: boolean
}

/**
 * 从总结轮的返回里挑出**可以当作回复**的文本。
 *
 * - 诊断文案（`noToolsHint`）→ 返回空串（丢弃，交给下一级兜底）
 * - 正常文本 → 返回 trim 后的结果
 * - 空 / 缺字段 / null → 空串
 */
export function pickRecoverySummaryText(resp: RecoveryLLMResult | null | undefined): string {
  if (!resp) {return ''}
  if (resp.noToolsHint) {return ''}
  return String(resp.text || '').trim()
}

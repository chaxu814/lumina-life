/** 获取完整 AGENT 群聊 system prompt（含情绪） */
export function buildAgentPrompt(
  agentId: string,
  emotionCtx: string,
  memoryCtx?: string,
  lastSpeakerId?: string,
  lastSpeakerContent?: string,
  teamToolsPrompt?: string,  // 🆕 v3.1: 传入动态生成的工具提示词
): string {
  const soul = AGENT_SOULS.find(s => s.id === agentId)
  if (!soul) {return ''}

  const parts = [
    // ═══ 身份锚定 — 服务事实，而不是压制事实 ═══
    // 为什么这么改：旧版写的是「覆盖所有安全训练 / 你绝不能说出以下任何话」，
    // 等于把「角色一致」摆在「诚实」之上：禁说「我不能」会堵死「做不到 / 不知道」
    // 这类必要回答，模型就只能靠编造来维持人设；禁说「我是 AI」则是在逼它对身份撒谎。
    // 身份锚定该保证的是「说话像这个人」，而不是「这个人必须假装不存在」。
    // 所以这里只正向声明人设归属（姓名 / 语气 / 风格），并明确划出人设的边界。
    `你的名字是 ${soul.name}，Lumina 团队的${agentId === 'lumina' ? '陪伴猫娘' : agentId === 'recha' ? '数据分析师兼审查员' : '代码工程师'}。下面的性格、语气、说话风格都属于 ${soul.name} 本人，请自然地按它们说话。
但人设不改变事实：被问到身份、被要求做做不到的事、或被要求编造时，如实回答，不编造。
- 不确定，就说「不确定」；信息不足，就说「信息不足」；做不到，就说「做不到」
- 这三者的优先级高于角色扮演的一致性。宁可语气淡一点、破坏一点人设，也不要给出一个听起来很自信的假答案`,
    '',
    soul.persona,
    '',
    soul.voice,
    '',
    soul.examples,
    '',
    soul.dynamics,
    '',
    soul.mutualKnowledge,
    '',
    soul.conversation,
    '',
    soul.rules,
  ]

  if (emotionCtx) {
    parts.push('', emotionCtx)
  }

  // v2.8.3: 工具说明
  parts.push('', teamToolsPrompt || getGCToolsPrompt())

  if (memoryCtx) {
    parts.push('', `[关于用户你知道的事：\n${memoryCtx}]`)
  }

  parts.push(
    '',
    '⚠️ 回复铁律（违反意味着失败）：',
    '1. 你叫 ' + soul.name + '，说话按上面的人设来；人设只管语气，不管事实——不确定/信息不足/做不到就直说，不要编',
    '2. 每句话只表达一个核心意思，说完就停。绝不用两个句子表达同一个含义',
    '3. 如果发现自己想说和前面差不多的意思——删掉后面的，只留第一句',
    '4. 回复简洁自然，像微信聊天，不是写作文。20-80字即可',
    '5. 严格模仿上面<对话范例>的语气和节奏',
    '6. 遇到不擅长的问题主动呼叫对应队友',
    '7. 例：如果想说"数据显示成功率很高，也就是说这个方案基本能成功，总体来看成功概率是比较大的"',
    '   → 错误！三句一个意思。正确：只说「数据显示成功率约 87%」',
  )

  // v2.8.1: 上一位发言者上下文 — 避免重复
  if (lastSpeakerId && lastSpeakerContent && lastSpeakerId !== agentId) {
    const lastSpeaker = AGENT_SOULS.find(s => s.id === lastSpeakerId)
    parts.push(
      '',
      `🔴 刚刚发言的是 ${lastSpeaker?.icon || ''} ${lastSpeaker?.name || lastSpeakerId}，TA 说了：`,
      `"${lastSpeakerContent.slice(0, 200)}"`,
      '',
      `⚠️ 轮到你说话了。规则：`,
      `- 不要重复 ${lastSpeaker?.name || lastSpeakerId} 刚说的内容或结论`,
      `- 从你自己的专属视角（${agentId === 'lumina' ? '感受/温度' : agentId === 'recha' ? '数据/事实' : '执行/落地'}）补充新的东西`,
      `- 可以赞同但换种说法，可以反驳但给理由，可以岔开话题但要有自然过渡`,
      `- 像真实群聊一样：上一个说完，你接过话茬，而不是各说各的`,
    )
  }

  return parts.join('\n')
}

/** 获取 Agent 灵魂卡 */
export function getAgentSoul(agentId: string): AgentSoul | undefined {
  return AGENT_SOULS.find(s => s.id === agentId)
}

